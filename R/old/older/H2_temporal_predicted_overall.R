# ============================================================
# HELPER: significance stars
# ============================================================
sig_stars <- function(p) {
  dplyr::case_when(
    p < 0.001 ~ "***",
    p < 0.01  ~ "**",
    p < 0.05  ~ "*",
    TRUE      ~ "ns"
  )
}

# ============================================================
# DATA PREPARATION
# ============================================================
cat("=== DATA PREPARATION ===\n\n")

# Identical join logic to H2_validation_aggregated_levels.R (Overall Level)
faird_ammod_paired <- data_list$etraps_daily_overlap %>%
  dplyr::filter(Device_type == "FAIRD") %>%
  dplyr::group_by(Date, Site) %>%
  dplyr::summarise(
    faird_biomass_mg = sum(biomass_mg,  na.rm = TRUE),
    faird_abundance  = sum(abundance,   na.rm = TRUE),
    .groups = "drop"
  ) %>%
  dplyr::inner_join(
    data_list$ammod_biomass_overlap %>%
      dplyr::select(Date, Site, ammod_live_mass = Live_mass),
    by = c("Date", "Site")
  ) %>%
  dplyr::filter(!is.na(ammod_live_mass)) %>%
  dplyr::filter(Site != "Site4") %>%
  dplyr::mutate(
    log_FAIRD = log10(faird_biomass_mg + 1),
    log_AMMOD = log10(ammod_live_mass  + 1),
    Site      = as.character(Site),
    Habitat   = dplyr::case_when(
      Site %in% c("Site1", "Site2") ~ "Maize",
      Site == "Site3"               ~ "Meadow",
      TRUE                          ~ NA_character_
    )
  )

cat("Overall Level paired observations:", nrow(faird_ammod_paired), "\n")
cat("Sites:", paste(sort(unique(faird_ammod_paired$Site)), collapse = ", "), "\n")
cat("n per site:\n")
print(table(faird_ammod_paired$Site))
cat("\n")

# ============================================================
# GLOBAL OLS REGRESSION
# ============================================================
cat("=== GLOBAL OLS REGRESSION ===\n\n")

fit_global <- lm(log_FAIRD ~ log_AMMOD, data = faird_ammod_paired)
fit_sum    <- summary(fit_global)

r2        <- fit_sum$r.squared
pval      <- fit_sum$coefficients["log_AMMOD", "Pr(>|t|)"]
intercept <- coef(fit_global)["(Intercept)"]
slope     <- coef(fit_global)["log_AMMOD"]
ci        <- confint(fit_global)["log_AMMOD", ]

cat(sprintf("  Intercept = %.4f\n", intercept))
cat(sprintf("  Slope     = %.4f [%.4f, %.4f]\n", slope, ci[1], ci[2]))
cat(sprintf("  R²        = %.3f %s\n\n", r2, sig_stars(pval)))

# Model equation printed for transparency
cat(sprintf(
  "  Equation: log10(FAIRD_pred + 1) = %.4f + %.4f * log10(AMMOD + 1)\n",
  intercept, slope
))
cat(sprintf(
  "  Back-transform: FAIRD_pred_mg = 10^(%.4f + %.4f * log10(AMMOD + 1)) - 1\n\n",
  intercept, slope
))

# ============================================================
# COMPUTE PREDICTED FAIRD VALUES
# ============================================================
cat("=== PREDICTED FAIRD CALCULATION ===\n\n")

faird_ammod_predicted <- faird_ammod_paired %>%
  dplyr::mutate(
    # Apply regression equation on log scale
    log_FAIRD_pred   = intercept + slope * log_AMMOD,
    # Back-transform to mg
    faird_pred_mg    = 10^log_FAIRD_pred - 1
  )

cat("Summary of predicted FAIRD biomass (mg):\n")
print(summary(faird_ammod_predicted$faird_pred_mg))
cat("\nSummary of observed FAIRD biomass (mg):\n")
print(summary(faird_ammod_predicted$faird_biomass_mg))

# Residuals in mg space (observed - predicted)
faird_ammod_predicted <- faird_ammod_predicted %>%
  dplyr::mutate(residual_mg = faird_biomass_mg - faird_pred_mg)

cat("\nResiduals (FAIRD_observed - FAIRD_predicted, mg):\n")
print(summary(faird_ammod_predicted$residual_mg))
cat("\n")

# ============================================================
# BUILD LONG FORMAT FOR PLOTTING
# ============================================================

# Three series: AMMOD observed, FAIRD observed, FAIRD predicted
temporal_long <- faird_ammod_predicted %>%
  dplyr::select(
    Date, Site,
    AMMOD           = ammod_live_mass,
    FAIRD           = faird_biomass_mg,
    FAIRD_predicted = faird_pred_mg
  ) %>%
  tidyr::pivot_longer(
    cols      = c(AMMOD, FAIRD, FAIRD_predicted),
    names_to  = "Method",
    values_to = "Biomass"
  ) %>%
  dplyr::mutate(
    Date   = as.Date(Date),
    Method = factor(Method, levels = c("AMMOD", "FAIRD", "FAIRD_predicted"))
  )

# Diagnostic: n per Method and Site
cat("Observations per Method and Site:\n")
print(table(temporal_long$Method, temporal_long$Site))
cat("\n")

# ============================================================
# FIGURE
# ============================================================
cat("=== GENERATING FIGURE ===\n\n")

# --- Subtitle string ---
# Spearman rho: retrieve from data (computed inline for subtitle)
spearman_rho   <- cor.test(faird_ammod_paired$log_FAIRD,
                           faird_ammod_paired$log_AMMOD,
                           method = "spearman", exact = FALSE)

# Kendall tau on daily changes (authoritative, from H2_validation_aggregated_levels.R)
# hardcoded here because this is a visualization-only script
tau_global  <- 0.187
tau_p_global <- 0.154

subtitle_text <- sprintf(
  "R\u00b2 = %.3f %s | Concordance: 55.0%% | Kendall \u03c4\u2020 = %.3f (p = %.4f)\nSteelblue line = FAIRD predicted from global OLS [intercept = %.3f, slope = %.3f]",
  r2, sig_stars(pval),
  tau_global, tau_p_global,
  intercept, slope
)

# --- Plot ---
p_temporal_predicted <- ggplot(
  temporal_long,
  aes(x     = Date,
      y     = Biomass,
      color = Method,
      linetype = Site,
      group = interaction(Method, Site))
) +
  # Lines for all three series
  geom_line(
    aes(linewidth = Method),
    na.rm = TRUE
  ) +
  # Points ONLY for observed series (not predicted)
  geom_point(
    data  = ~dplyr::filter(.x, Method != "FAIRD_predicted"),
    size  = 2.5,
    alpha = 0.85,
    na.rm = TRUE
  ) +
  # Color scale: use local_colors (extends custom_colors with FAIRD_predicted)
  scale_color_manual(
    values = local_colors,
    labels = c(
      AMMOD           = "AMMOD (observed)",
      FAIRD           = "FAIRD (observed)",
      FAIRD_predicted = "FAIRD (predicted from OLS)"
    ),
    name = "Series"
  ) +
  # Linetype for Site
  scale_linetype_manual(
    values = c(Site1 = "solid", Site2 = "dashed", Site3 = "dotdash"),
    name   = "Site"
  ) +
  # Linewidth: predicted line slightly thinner to visually subordinate it
  scale_linewidth_manual(
    values = c(
      AMMOD           = 1.0,
      FAIRD           = 1.0,
      FAIRD_predicted = 0.75
    ),
    guide = "none"   # do not show linewidth in legend
  ) +
  # Y axis: pseudo-log scale (handles zero values)
  scale_y_continuous(
    trans  = scales::pseudo_log_trans(base = 10, sigma = 1),
    labels = scales::comma,
    breaks = c(0, 10, 100, 1000, 5000, 10000)
  ) +
  scale_x_date(date_labels = "%b %d", date_breaks = "4 days") +
  labs(
    title    = "Overall Level — Temporal Concordance with Regression-Predicted FAIRD",
    subtitle = subtitle_text,
    x        = "Date",
    y        = "Biomass (mg)",
    caption  = "\u2020 Kendall \u03c4 computed on within-site daily changes (pooled across sites)"
  ) +
  theme_minimal(base_size = 11) +
  theme(
    plot.title       = element_text(face = "bold", size = 12),
    plot.subtitle    = element_text(size = 8.5, color = "gray35", lineheight = 1.3),
    plot.caption     = element_text(size = 8, color = "gray50", hjust = 0),
    legend.position  = "bottom",
    legend.box       = "vertical",
    panel.grid.minor = element_blank(),
    axis.text.x      = element_text(angle = 30, hjust = 1, size = 8)
  )

print(p_temporal_predicted)

