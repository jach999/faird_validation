# ==============================================================================
# H2_temporal_predicted_overall.R
# Overall Level — Temporal Concordance with Regression-Predicted FAIRD
#
# Purpose: Exploratory visualization that adds a FAIRD-predicted series to the
#          Overall Level temporal concordance plot. Predicted values are derived
#          from the global OLS equation fitted on log10(x+1) scale:
#            log10(FAIRD_pred + 1) = intercept + slope * log10(AMMOD + 1)
#          Back-transformed to mg for plotting alongside observed AMMOD and FAIRD.
#
#          Analogous to sensor calibration visualization: uses the reference
#          system (AMMOD) as input to the regression to generate a dynamic
#          "expected FAIRD" trajectory and compares it to what FAIRD actually
#          measured. The gap between observed and predicted is the model residual
#          expressed in temporal space.
#
# Input : data_cleaned.RData (generated by load_data.R)
#         custom_colors.R
# Output: PNG/PDF in outputs/
#
# Author : Juan Chiavassa (chiavass@agro.uba.ar)
# Created: 2026-03-20
# ==============================================================================

