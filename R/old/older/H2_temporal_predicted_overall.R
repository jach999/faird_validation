# ============================================================
# SECTION 2: TWO-PANEL FIGURE — SCATTER + TEMPORAL RESIDUALS
# ============================================================
# Panel A: OLS scatter (log scale), identical to make_pooled_scatter() style.
# Panel B: Log-scale residuals over time per site.
#   Residual = log10(FAIRD_obs + 1) - log10(FAIRD_pred + 1)
#            = actual OLS residual (what the regression minimized).
#   Horizontal reference at 0 = perfect agreement.
#   Lines ± 0.3 = approximate 2x departure from prediction (visual guide).
#   Points colored by Site; horizontal band shaded for ±0.3 zone.
# ============================================================

cat("=== GENERATING TWO-PANEL FIGURE (Scatter + Residuals) ===\n\n")

# --- Log-scale residuals ---
faird_ammod_predicted <- faird_ammod_predicted %>%
  dplyr::mutate(
    log_resid = log_FAIRD - log_FAIRD_pred   # actual OLS residual
  )

cat("Log-scale residuals summary:\n")
print(summary(faird_ammod_predicted$log_resid))
cat(sprintf("  n positive (FAIRD > predicted): %d\n",
            sum(faird_ammod_predicted$log_resid > 0)))
cat(sprintf("  n negative (FAIRD < predicted): %d\n",
            sum(faird_ammod_predicted$log_resid < 0)))
cat(sprintf("  |residual| > 0.3 log units:     %d\n\n",
            sum(abs(faird_ammod_predicted$log_resid) > 0.3)))

# --- Panel A: Scatter ---
annot_text <- sprintf(
  "R\u00b2 = %.3f %s\n\u03c1 = %.3f %s\n\u03c4\u2020 = %.3f ns\nConcordance = 55.0%%",
  r2, sig_stars(pval),
  spearman_rho$estimate, sig_stars(spearman_rho$p.value),
  tau_global
)

p_scatter <- ggplot(
  faird_ammod_predicted,
  aes(x = log_AMMOD, y = log_FAIRD, color = Site)
) +
  geom_point(size = 3, alpha = 0.75) +
  geom_smooth(
    aes(group = 1),
    method    = "lm",
    formula   = y ~ x,
    se        = TRUE,
    color     = "gray30",
    fill      = "gray70",
    alpha     = 0.25,
    linewidth  = 1
  ) +
  scale_color_manual(values = custom_colors, name = "Site") +
  annotate(
    "text",
    x = -Inf, y = Inf,
    label    = annot_text,
    hjust    = -0.08, vjust = 1.15,
    size     = 3.2,
    fontface = "italic",
    lineheight = 1.3
  ) +
  labs(
    title = "A) Overall Level — OLS Scatter",
    subtitle = "Site covariate not significant (all p > 0.64) — pooling validated",
    x = "log\u2081\u2080(AMMOD Live Mass + 1)",
    y = "log\u2081\u2080(FAIRD Biomass + 1)"
  ) +
  theme_minimal(base_size = 11) +
  theme(
    plot.title    = element_text(face = "bold", size = 12),
    plot.subtitle = element_text(color = "gray40", size = 9),
    legend.position = "right"
  )

# --- Panel B: Temporal residuals ---
p_residuals <- ggplot(
  faird_ammod_predicted,
  aes(x        = as.Date(Date),
      y        = log_resid,
      color    = Site,
      linetype = Site,
      group    = Site)
) +
  # Reference band ± 0.3 log units (~2x departure)
  annotate(
    "rect",
    xmin = -Inf, xmax = Inf,
    ymin = -0.3, ymax =  0.3,
    fill  = "gray90", alpha = 0.5
  ) +
  # Zero line
  geom_hline(yintercept = 0, color = "gray40", linewidth = 0.7, linetype = "solid") +
  # ± 0.3 guide lines
  geom_hline(yintercept =  0.3, color = "gray60", linewidth = 0.4, linetype = "dashed") +
  geom_hline(yintercept = -0.3, color = "gray60", linewidth = 0.4, linetype = "dashed") +
  # Residual lines and points
  geom_line(linewidth = 1, na.rm = TRUE) +
  geom_point(size = 2.5, alpha = 0.85, na.rm = TRUE) +
  scale_color_manual(values = custom_colors, name = "Site") +
  scale_linetype_manual(
    values = c(Site1 = "solid", Site2 = "dashed", Site3 = "dotdash"),
    name   = "Site"
  ) +
  scale_x_date(date_labels = "%b %d", date_breaks = "4 days") +
  labs(
    title    = "B) Temporal Residuals (log scale)",
    subtitle = "Residual = log\u2081\u2080(FAIRD\u2080\u209b\u209b + 1) \u2212 log\u2081\u2080(FAIRD\u209a\u2090\u2091\u1d48 + 1) | Grey band = \u00b10.3 log units (\u22482\u00d7 departure)",
    x        = "Date",
    y        = "Residual (log\u2081\u2080 units)",
    caption  = "\u2020 Kendall \u03c4 computed on within-site daily changes (pooled across sites)"
  ) +
  theme_minimal(base_size = 11) +
  theme(
    plot.title       = element_text(face = "bold", size = 12),
    plot.subtitle    = element_text(color = "gray40", size = 8.5),
    plot.caption     = element_text(size = 8, color = "gray50", hjust = 0),
    legend.position  = "right",
    panel.grid.minor = element_blank(),
    axis.text.x      = element_text(angle = 30, hjust = 1, size = 8)
  )

# --- Combine ---
fig_two_panel <- p_scatter + p_residuals +
