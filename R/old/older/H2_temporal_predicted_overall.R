  patchwork::plot_annotation(
    title    = "H2 Inter-Method Validation: Overall Level",
    subtitle = "Left: pooled OLS on log scale | Right: per-site OLS residuals over time",
    theme    = theme(
      plot.title    = element_text(face = "bold", size = 13),
      plot.subtitle = element_text(size = 9, color = "gray40")
    )
  )

print(fig_two_panel)

ggsave("outputs/H2_Overall_Scatter_Residuals.png",
