# Significance stars
sig_stars <- function(p) {
  dplyr::case_when(
    p < 0.001 ~ "***",
    p < 0.01  ~ "**",
    p < 0.05  ~ "*",
    TRUE      ~ "ns"
  )
}

# Full OLS regression + non-parametric correlations + diagnostics
# Used for both site-level verification and pooled levels.
run_ols_analysis <- function(df, label) {
  
  n <- nrow(df)
  cat(sprintf("\n--- %s (n = %d) ---\n", label, n))
  
  if (n < 4) {
    cat("  Insufficient data — skipping.\n")
    return(invisible(NULL))
  }
  
  # OLS on log10(x+1) scale
  fit      <- lm(log_FAIRD ~ log_AMMOD, data = df)
  fit_sum  <- summary(fit)
  r2       <- fit_sum$r.squared
  adj_r2   <- fit_sum$adj.r.squared
  pval     <- fit_sum$coefficients["log_AMMOD", "Pr(>|t|)"]
  slope    <- coef(fit)["log_AMMOD"]
  ci       <- confint(fit)["log_AMMOD", ]
  intercept <- coef(fit)["(Intercept)"]
  
  # Diagnostics
  shapiro_p <- shapiro.test(residuals(fit))$p.value
  bp_p      <- car::ncvTest(fit)$p
  dw_obj    <- lmtest::dwtest(fit)
  dw_stat   <- as.numeric(dw_obj$statistic)
  dw_p      <- dw_obj$p.value
  
  # Non-parametric (on log scale)
  # NOTE: Kendall tau is NOT computed here — must be computed on daily changes
  # via run_temporal_sync(), consistent with H2_validation_FAIRD_AMMOD.R.
  spearman <- cor.test(df$log_FAIRD, df$log_AMMOD, method = "spearman",
                       exact = FALSE)
  
  cat(sprintf("  R² = %.3f %s | Adj.R² = %.3f\n",
              r2, sig_stars(pval), adj_r2))
  cat(sprintf("  Slope = %.3f [%.3f, %.3f] | Intercept = %.3f\n",
              slope, ci[1], ci[2], intercept))
  cat(sprintf("  Spearman ρ = %.3f (p = %.4f %s)\n",
              spearman$estimate, spearman$p.value, sig_stars(spearman$p.value)))
  cat(sprintf("  Diagnostics: Shapiro p = %.3f | BP p = %.3f | DW = %.3f (p = %.3f)\n",
              shapiro_p, bp_p, dw_stat, dw_p))
  
  list(
    label      = label,
    n          = n,
    r2         = r2,
    adj_r2     = adj_r2,
    p_ols      = pval,
    slope      = slope,
    ci_low     = ci[1],
    ci_high    = ci[2],
    intercept  = intercept,
    spearman   = spearman$estimate,
    spearman_p = spearman$p.value,
    shapiro_p  = shapiro_p,
    bp_p       = bp_p,
    dw_stat    = dw_stat,
    dw_p       = dw_p,
    fit        = fit,
    data       = df
  )
}

# Site covariate model — validates that pooling is appropriate
# (pooling valid if site effect is ns after controlling for AMMOD)
run_covariate_model <- function(df, label) {
  cat(sprintf("\n  Site covariate model: log_FAIRD ~ log_AMMOD + Site [%s]\n", label))
  fit_cov <- lm(log_FAIRD ~ log_AMMOD + Site, data = df)
  print(round(summary(fit_cov)$coefficients, 4))
  invisible(fit_cov)
}

# Kendall tau on DAILY CHANGES (per-site lag, then pool changes)
# Consistent with analyze_temporal_sync() in H2_validation_FAIRD_AMMOD.R
run_temporal_sync <- function(df, label) {
  
  changes <- df %>%
    dplyr::arrange(Site, Date) %>%
    dplyr::group_by(Site) %>%
    dplyr::mutate(
      FAIRD_change = faird_biomass_mg - dplyr::lag(faird_biomass_mg),
      AMMOD_change = ammod_live_mass  - dplyr::lag(ammod_live_mass),
      concordant   = sign(FAIRD_change) == sign(AMMOD_change)
    ) %>%
    dplyr::ungroup() %>%
    dplyr::filter(!is.na(FAIRD_change))
  
  n_changes   <- nrow(changes)
  concordance <- 100 * sum(changes$concordant, na.rm = TRUE) / n_changes
  kt          <- cor.test(changes$FAIRD_change, changes$AMMOD_change,
                          method = "kendall", exact = FALSE)
  
  cat(sprintf("\n  Temporal sync [%s]: n changes = %d\n", label, n_changes))
  cat(sprintf("  Concordance = %.1f%% | Kendall τ = %.3f (p = %.4f %s)\n",
              concordance, kt$estimate, kt$p.value, sig_stars(kt$p.value)))
  
  list(
    n_changes   = n_changes,
    concordance = concordance,
    tau         = as.numeric(kt$estimate),
    tau_p       = kt$p.value
  )
}

