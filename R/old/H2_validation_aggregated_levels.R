# --- Shared scatter plot function for pooled levels ---
# Points colored by Site for traceability; regression line for pooled data.
make_pooled_scatter <- function(df, result, sync, panel_label, subtitle_hint = "") {
  
  plot_data <- df %>%
    dplyr::mutate(
      Site_label = Site,
      Date_label = format(as.Date(Date), "%b %d")
    )
  
  r2_sig   <- sig_stars(result$p_ols)
  tau_sig  <- sig_stars(sync$tau_p)
  rho_sig  <- sig_stars(result$spearman_p)
  
  annot <- sprintf(
    "R\u00b2 = %.3f %s\n\u03c1 = %.3f %s\n\u03c4\u2020 = %.3f %s\nConcordance = %.1f%%",
    result$r2,       r2_sig,
    result$spearman, rho_sig,
    sync$tau,        tau_sig,
    sync$concordance
  )
  
  ggplot(plot_data, aes(x = log_AMMOD, y = log_FAIRD, color = Site_label)) +
    geom_point(size = 3, alpha = 0.75) +
    geom_smooth(
      aes(group = 1),        # single pooled regression line
      method  = "lm",
      formula = y ~ x,
      se      = TRUE,
      color   = "gray30",
      fill    = "gray70",
      alpha   = 0.25,
      linewidth = 1
    ) +
    scale_color_manual(
      values = custom_colors,
      name   = "Site"
    ) +
    labs(
      title    = panel_label,
      subtitle = subtitle_hint,
      x        = "log\u2081\u2080(AMMOD Live Mass + 1)",
      y        = "log\u2081\u2080(FAIRD Biomass + 1)"
    ) +
    annotate(
      "text",
      x = -Inf, y = Inf,
      label  = annot,
      hjust  = -0.08, vjust = 1.15,
      size   = 3.2,
      fontface = "italic",
      lineheight = 1.3
    ) +
    theme_minimal(base_size = 11) +
    theme(
      plot.title    = element_text(face = "bold"),
      plot.subtitle = element_text(color = "gray40", size = 9),
      legend.position = "right"
    )
}

# --- Shared temporal concordance plot for pooled levels ---
make_pooled_temporal <- function(df, result, sync, panel_label) {
  
  temporal_data <- df %>%
    dplyr::select(Date, Site, FAIRD = faird_biomass_mg, AMMOD = ammod_live_mass) %>%
    tidyr::pivot_longer(cols = c(FAIRD, AMMOD),
                        names_to  = "Method",
                        values_to = "Biomass")
  
  subtitle_text <- sprintf(
    "R\u00b2 = %.3f | Concordance: %.1f%% | Kendall \u03c4\u2020 = %.3f (p = %.4f)",
    result$r2, sync$concordance, sync$tau, sync$tau_p
  )
  
  ggplot(temporal_data, aes(x = as.Date(Date), y = Biomass,
                            color = Method, linetype = Site, group = interaction(Method, Site))) +
    geom_line(linewidth = 1) +
    geom_point(size = 2.5, alpha = 0.8) +
    scale_color_manual(
      values = custom_colors,
      name = "Device Type"
    ) +
    scale_linetype_manual(
      values = c(Site1 = "solid", Site2 = "dashed", Site3 = "dotdash"),
      name   = "Site"
    ) +
    scale_y_continuous(
      trans  = scales::pseudo_log_trans(base = 10, sigma = 1),
      labels = scales::comma,
      breaks = c(0, 10, 100, 1000, 5000, 10000)
    ) +
    scale_x_date(date_labels = "%b %d", date_breaks = "4 days") +
    labs(
      title    = panel_label,
      subtitle = subtitle_text,
      x        = "Date",
      y        = "Biomass (mg)"
    ) +
    theme_minimal(base_size = 11) +
    theme(
      plot.title       = element_text(face = "bold", size = 12),
      plot.subtitle    = element_text(size = 9, color = "gray40"),
      legend.position  = "bottom",
      panel.grid.minor = element_blank(),
      axis.text.x      = element_text(angle = 30, hjust = 1, size = 8)
    )
}

