# Bootstrap confidence intervals for R² (pooled models only)
bootstrap_r2 <- function(df, n_boot = 1000, seed = 42) {
  set.seed(seed)
  r2_boot <- replicate(n_boot, {
    idx     <- sample(nrow(df), replace = TRUE)
    df_boot <- df[idx, ]
    summary(lm(log_FAIRD ~ log_AMMOD, data = df_boot))$r.squared
  })
  q <- quantile(r2_boot, c(0.025, 0.975))
  c(mean  = mean(r2_boot),
    ci_lo = unname(q[1]),
    ci_hi = unname(q[2]))
}

